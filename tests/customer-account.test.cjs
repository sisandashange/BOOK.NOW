"use strict";
const fs = require("fs");
const path = require("path");
const assert = require("node:assert/strict");
const read = file => fs.readFileSync(path.join(__dirname, "..", file), "utf8");
const nav = read("customer-account.js");
const account = read("account.html");
const migration = read("supabase/migrations/20261124090000_optional_customer_accounts.sql");
const store = read("store.html");
const index = read("index.html");

assert.ok(nav.includes("touchstart") && nav.includes("touchend"), "Drawer must support edge swipe gestures");
assert.ok(nav.includes("aria-expanded") && nav.includes("Escape"), "Drawer must expose accessible state and keyboard close");
assert.ok(nav.includes("list_my_customer_bookings"), "Account page must load private booking history through RPC");
assert.ok(nav.includes("claim_customer_booking"), "Account page must support linking earlier guest bookings");
assert.ok(nav.includes("signUp") && nav.includes("signInWithPassword"), "Optional email/password account registration and login must work");
assert.ok(account.includes("An account is optional"), "Account page must clearly say registration is optional");
assert.ok(account.includes("Link an earlier guest booking"), "Account page must explain legacy booking linking");
assert.ok(migration.includes("customer_user_id uuid") && migration.includes("REFERENCES auth.users"), "Bookings must support nullable auth ownership");
assert.ok(migration.includes("NEW.customer_user_id := auth.uid()"), "Database must derive booking owner from authenticated session");
assert.ok(migration.includes("customer_user_id = auth.uid()"), "History RPC must restrict records to the signed-in owner");
assert.ok(migration.includes("v_owner <> auth.uid()"), "Claiming must not steal a booking already linked to another account");
assert.ok(migration.includes("GRANT EXECUTE ON FUNCTION public.claim_customer_booking(text, text) TO authenticated"), "Claim RPC must not be available to guests");
assert.ok(!migration.includes("GRANT SELECT ON TABLE public.bookings TO authenticated"), "Customer accounts must not gain broad direct booking table access");
assert.ok(store.includes("customer-account.js") && index.includes("customer-account.js"), "Drawer must load on both marketplace and shop booking pages");
console.log("Customer account and drawer regression checks passed.");
